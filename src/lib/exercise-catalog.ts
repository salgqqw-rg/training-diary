// Ссылка на видео → способ показа: встраиваемый плеер, файл или просто ссылка
export type VideoView = { kind: "iframe" | "file" | "link"; src: string };
export function videoView(raw: string | null | undefined): VideoView | null {
  const url = (raw ?? "").trim();
  if (!/^https?:\/\//i.test(url)) return null;
  let u: URL;
  try { u = new URL(url); } catch { return null; }
  const host = u.hostname.replace(/^www\.|^m\./, "");
  if (host === "youtu.be") return { kind: "iframe", src: `https://www.youtube.com/embed/${u.pathname.slice(1)}` };
  if (host === "youtube.com") {
    const id = u.searchParams.get("v") ?? u.pathname.match(/^\/(?:shorts|embed)\/([\w-]+)/)?.[1];
    if (id) return { kind: "iframe", src: `https://www.youtube.com/embed/${id}` };
  }
  if (host === "rutube.ru") {
    const id = u.pathname.match(/^\/(?:video|play\/embed)\/([\w]+)/)?.[1];
    if (id) return { kind: "iframe", src: `https://rutube.ru/play/embed/${id}` };
  }
  if (/\.(mp4|webm|mov)$/i.test(u.pathname)) return { kind: "file", src: url };
  return { kind: "link", src: url };
}

